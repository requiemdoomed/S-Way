def write_index():
    """notebooks/index.json — read by the in-app Research notebooks viewer."""
    import datetime
    import json
    entries = []
    for name in sorted(NOTEBOOKS):
        path = NB / name
        if not path.exists():
            continue
        nb = nbformat.read(path, 4)
        first = next((c for c in nb.cells if c.cell_type == "markdown"), None)
        title = first.source.splitlines()[0].lstrip("# ").strip() if first else name
        entries.append({"file": name, "title": title, "summary": SUMMARIES.get(name, "")})
    (NB / "index.json").write_text(json.dumps({"generated": datetime.date.today().isoformat(), "notebooks": entries}, indent=2))


def build(run: bool, only=None):
    from nbclient import NotebookClient
    for name, cells in NOTEBOOKS.items():
        if only and not any(o in name for o in only):
            continue
        nb = new_notebook(cells=cells, metadata={"kernelspec": {"name": "python3", "display_name": "Python 3", "language": "python"}, "language_info": {"name": "python"}})
        path = NB / name
        if run:
            print("executing", name, flush=True)
            NotebookClient(nb, timeout=1800, kernel_name="python3", resources={"metadata": {"path": str(NB)}}).execute()
        nbformat.write(nb, path)
    write_index()


